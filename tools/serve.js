#!/usr/bin/env node
/** Servidor estático mínimo para probar el juego: node tools/serve.js [puerto] [carpeta] */
'use strict';
const http = require('http');
const fs = require('fs');
const path = require('path');
const port = Number(process.argv[2] || 8123);
const root = path.resolve(process.argv[3] || path.join(__dirname, '..', 'src'));
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png' };
http.createServer((req, res) => {
  let p = decodeURIComponent(req.url.split('?')[0]);
  if (p.endsWith('/')) p += 'index.html';
  const file = path.join(root, path.normalize(p));
  if (!file.startsWith(root)) { res.writeHead(403); return res.end(); }
  fs.readFile(file, (err, data) => {
    if (err) { res.writeHead(404); return res.end('No encontrado'); }
    res.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
    res.end(data);
  });
}).listen(port, () => console.log(`Sirviendo ${root} en http://localhost:${port}`));
